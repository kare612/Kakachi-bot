import axios from 'axios';

export default {
    command: ['الاوامر', 'menu', 'أوامر', 'help', 'قائمة'],
    category: 'user',
    async default({ sock, msg, args }) {
        const chatJid = msg.key.remoteJid;
        
        const menuText = `
*⚡ بـوت كـاكـاشـي الـمـطـور ⚡*

👋 ¦ مـرحـبـاً بـك فـي قـائـمـة الـتـحـكـم الشاملة.
📊 ¦ إجمالي الإضافات المتاحة: *700 أمر برمجي*

*👑 قـسـم الـمـطـور*
├• \`.اذاعه\` ¦ نشر إعلان لجميع الجروبات.
├• \`.بان\` ¦ حظر مستخدم من استخدام البوت.
├• \`.فك_بان\` ¦ إلغاء الحظر عن مستخدم.

*🛡️ قـسـم الإشـراف والجروبات*
├• \`.طرد\` ¦ إزالة عضو بالمنشن.
├• \`.رفع_مشرف\` ¦ ترقية عضو إلى مشرف.
├• \`.قفل\` ¦ إغلاق الشات للمشرفين.
├• \`.فتح\` ¦ فتح الشات للجميع.

*🎮 محرك الألعاب والتسلية*
├• \`.زوجني\` ¦ اختيار زوج/زوجة عشوائي بالصور!
├• \`.نسبة_الحب\` ¦ قياس نسبة الحب بين شخصين.
├• \`.سؤال\` ¦ لعبة سؤال وجواب تفاعلية.

*🎨 قسم الوسائط والتنزيلات*
├• \`.صورة\` ¦ جلب صورة عشوائية ومميزة.
├• \`.تحميل\` ¦ تنزيل الفيديوهات والمقاطع الصوتية.
├• \`.ملصق\` ¦ تحويل أي صورة إلى ملصق واتساب.

*👤 قـسـم الأعـضـاء والدعم*
├• \`.بينج\` ¦ فحص سرعة استجابة البوت.
├• \`.رتبتي\` ¦ فحص صلاحياتك الحالية.

💡 ¦ _تنويه: البوت يحتوي على أكثر من 700 أمر فرعي مدمج للعمل التلقائي الذكي._
✨ ¦ _تم التطوير بواسطة كاكاشي الأسطوري_
        `.trim();

        try {
            // رابط بديل ومباشر للصورة على سيرفر خارجي مفتوح ومستقر
            const response = await axios.get('https://imgbox.com', { 
                responseType: 'arraybuffer',
                headers: { 'User-Agent': 'Mozilla/5.0' }
            });
            const imageBuffer = Buffer.from(response.data, 'binary');

            await sock.sendMessage(chatJid, { 
                image: imageBuffer,
                caption: menuText
            }, { quoted: msg });
            
        } catch (error) {
            console.error("خطأ في تحميل الصورة، جاري إرسال النص فقط:", error);
            await sock.sendMessage(chatJid, { text: menuText }, { quoted: msg });
        }
    }
};
