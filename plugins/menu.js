import axios from 'axios';

export default {
    command: ['الاوامر', 'menu', 'أوامر', 'help', 'قائمة'],
    category: 'user',
    async default({ sock, msg, args }) {
        const chatJid = msg.key.remoteJid;
        
        const menuText = `
╭━━━〔 ⚡ *بـوت كـاكـاشـي الـمـطـور* ⚡ 〕━━━╮

      👋 ¦ مـرحـبـاً بـك فـي قـائـمـة الـتـحـكـم.
      📊 ¦ إجمالي الإضافات المتاحة: *700 أمر برميجي*

🤖 *〔 قـسـم الـذكـاء الاصـطـنـاعـي 〕*
├• \`.ذكاء\` ¦ اسأل ذكاء كاكاشي الاصطناعي عن أي شيء.
├• \`.ai\` ¦ تفاعل فوري وحل المشكلات البرمجية.

👑 *〔 قـسـم الـمـطـور والـتـحـكـم 〕*
├• \`.اذاعه\` ¦ نشر إعلان لجميع المجموعات.
├• \`.بان\` ¦ حظر مستخدم من استخدام البوت.
├• \`.فك_بان\` ¦ إلغاء الحظر عن مستخدم محظور.

🛡️ *〔 قـسـم الإشـراف والـمـجـمـوعـات 〕*
├• \`.طرد\` ¦ إزالة عضو خارج المجموعة بالمنشن.
├• \`.رفع_مشرف\` ¦ ترقية عضو إلى مشرف الجروب.
├• \`.قفل\` ¦ إغلاق الشات (للمشرفين فقط).
├• \`.فتح\` ¦ فتح الشات لإرسال رسائل الجميع.

🎮 *〔 مـحـرك الألـعـاب والـتـسـلـيـة 〕*
├• \`.زوجني\` ¦ اختيار زوج أو زوجة عشوائياً.
├• \`.نسبة_الحب\` ¦ قياس نسبة الحب بالمنشن بين شخصين.
├• \`.سؤال\` ¦ لعبة سؤال وجواب تفاعلية ذكية.

🎨 *〔 قـسـم الـوسـائـط والـتـنـزيـلات 〕*
├• \`.صوت\` ¦ تنزيل مقاطع الصوت والأغاني المباشرة.
├• \`.فيديو\` ¦ تحميل مقاطع الفيديو عالية الدقة.
├• \`.تنزيل\` ¦ سحب المقاطع من تيك توك وإنستغرام.
├• \`.ملصق\` ¦ تحويل الصور إلى ملصقات محلياً فوراً.

👤 *〔 قـسـم الأعـضـاء والـدعـم 〕*
├• \`.بينج\` ¦ فحص سرعة استجابة واتصال البوت.
├• \`.رتبتي\` ¦ فحص صلاحيات ورتبة المستخدم الحالية.

╰━━━━━━━━━━━━━━━━━━━━━━━━━━━━━╯
💡 ¦ _تنويه: البوت مجهز للعمل التلقائي والذكي في المجموعات._
✨ ¦ _تم التطوير والزخرفة بواسطة كاكاشي الأسطوري_
        `.trim();

        try {
            // رابط الصورة المباشر والجديد الشغال 100% الذي أرسلته
            const imageUrl = 'https://i.ibb.co/dJDHbPpS/62674.jpg';
            
            const response = await axios.get(imageUrl, { 
                responseType: 'arraybuffer',
                headers: { 'User-Agent': 'Mozilla/5.0' }
            });
            const imageBuffer = Buffer.from(response.data, 'binary');

            await sock.sendMessage(chatJid, { 
                image: imageBuffer,
                caption: menuText
            }, { quoted: msg });
            
        } catch (error) {
            console.error("خطأ في تحميل الصورة، جاري إرسال النص فقط:", error);
            await sock.sendMessage(chatJid, { text: menuText }, { quoted: msg });
        }
    }
};
