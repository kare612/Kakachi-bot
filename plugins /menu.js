import fs from 'fs';

export default {
  name: 'الاوامر',
  alias: ['أوامر', 'اوامر', 'قائمة', 'menu', 'help'],
  category: 'main',
  desc: 'عرض اللوحة البرمجية وكافة الأوامر المضافة للبوت',
  async execute(client, m, args) {
    try {
      // 1. التحقق الديناميكي الذكي من بنية الرسالة لضمان جلب البيانات بشكل صحيح
      const messageObj = m.message ? m : (Array.isArray(m) ? m[0] : m);
      if (!messageObj) return;

      // 2. استخراج المعرفات والبيانات الأساسية للمرسل والمحادثة
      const chatJid = messageObj.key.remoteJid;
      const userId = messageObj.key.participant || messageObj.participant || chatJid;
      
      const userLevel = global.db?.users?.[userId]?.level || 1;
      const userMoney = global.db?.users?.[userId]?.money || 0;

      // 3. بناء نص الرسالة المنسق والمزخرف
      const menuHeader = `⚡ *لوحة تحكم أوامر بوت كاكاشي المتطور* ⚡\n\n` +
                         `👤 *اللاعب:* @${userId.split('@')[0]}\n` +
                         `⭐ *المستوى:* [ ${userLevel} ] | 💰 *الرصيد:* $${userMoney}\n` +
                         `🗓️ *التاريخ:* ${new Date().toLocaleDateString('ar-EG')}\n` +
                         `===============================\n\n`;

      const menuBody = `🎬 *📂 قسم الميديا والفيديوهات (video.js)*\n` +
                       `• *.فيديو [الرابط]* — تحميل وتشغيل الفيديوهات من الروابط مباشرة.\n\n` +
                       
                       `🎮 *📂 قسم الألعاب التفاعلية (games.js)*\n` +
                       `• *.العاب* — عرض قائمة الألعاب المتاحة.\n` +
                       `• *.العاب زواج* — اختيار زوجين عشوائيين من الجروب بالصور.\n` +
                       `• *.العاب خمن* — بدء لعبة تخمين الصور والرموز التحدي.\n\n` +
                       
                       `⚔️ *📂 قسم النقابات والاشتراك (guilds.js)*\n` +
                       `• *.نقابة* — فتح اللوحة الإدارية للنقابات والعصابات.\n` +
                       `• *.نقابة إنشاء [الاسم]* — تأسيس نقابة جديدة خاصة بك.\n` +
                       `• *.نقابة انضمام [الاسم]* — طلب دخول نقابة مقاتلين.\n` +
                       `• *.نقابة تأكيد* — تفعيل البوت بعد الاشتراك في قناة الواتساب.\n\n` +
                       
                       `📊 *📂 قسم أرقام الألعاب (games_db.js)*\n` +
                       `• *.أرقام* — عرض ملف الأرقام الشخصي والمستوى الحالي.\n` +
                       `• *.أرقام ترتيب* — عرض توب 5 لأغنى أساطير السيرفر.\n` +
                       `• *.أرقام هدايا* — استلام الراتب والمكافأة اليومية للألعاب.\n\n` +
                       
                       `🤖 *📂 قسم الذكاء الاصطناعي (ai.js)*\n` +
                       `• *.ذكاء [السؤال]* — الرد الآلي والمحادثة مع الذكاء كاكاشي-GPT.\n` +
                       `• *.رسم [الوصف]* — تخيل وتوليد صور بجودة كاملة بالذكاء.\n\n` +
                       
                       `🛠️ *📂 قسم الأدوات والتحويل (toimage.js)*\n` +
                       `• *.لصورة* — تحويل الملصق إلى صورة بجودة عالية.\n\n` +
                       
                       `📦 *📂 قسم تحميل التطبيقات (apk.js)*\n` +
                       `• *.تطبيق [الاسم]* — البحث عن برامج وألعاب الأندرويد وتحميلها كملف APK.\n\n`;

      const menuFooter = `===============================\n` +
                         `📢 *قناتنا الرسمية المربوطة بالبوت:* \n` +
                         `🔗 https://whatsapp.com \n\n` +
                         `💡 _اكتب النقطة (.) قبل أي أمر لتشغيله بدقة وعمل كود معالجة سليم._`;

      const fullMenu = menuHeader + menuBody + menuFooter;

      // 4. إرسال الرسالة إلى شات الواتساب مع المنشن والرد المباشر (Quoted)
      await client.sendMessage(chatJid, { 
        text: fullMenu,
        mentions: [userId]
      }, { quoted: messageObj });

    } catch (error) {
      console.error("❌ خطأ أثناء تنفيذ أمر القائمة المحدث:", error);
    }
  }
};
